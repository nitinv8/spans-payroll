// Builds supabase/seed.private.sql from data/sheet-import.ts:
// employees, salary structures (effective 1 Apr 2026), default formulas, OT log,
// and April–September 2026 as finalized payroll runs.
// Usage: npm run seed -- you@spans.co.in other@spans.co.in   (emails allowed to log in)
import { writeFileSync } from "node:fs";
import { SHEET_FORMULAS_FY26, monthLabel } from "../lib/payroll";
import { computeLine, snapshotOf, type Employee } from "../lib/run-logic";
import { EMPLOYEES, STRUCTURES, HISTORY, ORGZIT, EXCLUDE_FROM_BANK_FILE, EMPLOYEE_NOTES, OT_LOG, PAYMENT_DATES } from "../data/sheet-import";
import { toStructure } from "../data/to-structure";
import { parseSheetDate } from "./sheet-date";

const allowed = process.argv.slice(2);
if (!allowed.length) allowed.push("nverma@spans.co.in");

const q = (v: unknown) => (v == null || v === "" ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
const emp = (code: string) => `(select id from employees where emp_code = ${q(code)})`;
const blank = (v: string) => (/^(not applicable|not eligible)$/i.test(v.trim()) ? "" : v.trim());

const out: string[] = [
  "-- GENERATED by scripts/make-seed.ts – contains personal data. Do not commit.",
  "begin;",
];

for (const a of allowed) out.push(`insert into app_users (email) values (${q(a.toLowerCase())}) on conflict do nothing;`);

out.push(`insert into formula_sets (effective_from, name, formulas, notes) values ('2026-04-01', 'FY2026-27 (from Google Sheet)', ${j(SHEET_FORMULAS_FY26)}, 'Reproduces the FY2026-27 Salary Sheet formulas') on conflict (effective_from) do nothing;`);

const employees: Record<string, Employee> = {};
EMPLOYEES.forEach((e, i) => {
  const advice = ["Emp 1", "Emp 2", "Emp 3"].includes(e.code) ? e.email : "team@spans.co.in";
  const row = {
    emp_code: e.code, name: e.name, father_name: e.father_name, designation: e.designation, location: e.location,
    status: e.status, dob: parseSheetDate(e.dob), date_of_joining: parseSheetDate(e.doj), date_of_leaving: parseSheetDate(e.dol),
    mobile: e.mobile, email: e.email, bank_advice_email: advice, bank_account: e.bank_account.replace(/\s/g, ""),
    ifsc: e.ifsc.trim().toUpperCase(), aadhaar: e.aadhaar, pan: e.pan, uan: blank(e.uan), esic_number: blank(e.esic_number),
    blood_group: e.blood_group, tshirt_size: e.tshirt_size, shoe_size: e.shoe_size, tshirt_status: e.tshirt_status,
    id_card: e.id_card, epf_kyc: e.epf_kyc, orgzit_description: ORGZIT[e.code]?.[0] ?? null, orgzit_id: ORGZIT[e.code]?.[1] ?? null,
    include_in_bank_file: !EXCLUDE_FROM_BANK_FILE.includes(e.code), sort_order: (i + 1) * 10,
    notes: [EMPLOYEE_NOTES[e.code], e.code === "Emp 47" ? "Orgzit ID in the sheet was Mohit's (maobf7eev9) – please verify." : null,
      !STRUCTURES[e.code] ? "No salary structure in the sheet – add one before running payroll." : null].filter(Boolean).join(" ") || null,
  };
  const cols = Object.keys(row);
  out.push(`insert into employees (${cols.join(", ")}) values (${cols.map((c) => (typeof (row as any)[c] === "boolean" || typeof (row as any)[c] === "number" ? String((row as any)[c]) : q((row as any)[c]))).join(", ")}) on conflict (emp_code) do nothing;`);
  employees[e.code] = { id: "", ...row, bank_name: null } as unknown as Employee;
});

for (const [code, s] of Object.entries(STRUCTURES)) {
  const t = toStructure(s);
  out.push(`insert into salary_structures (employee_id, effective_from, basic, hra, medical, conveyance, mobile, site_allowance, supervisor_allowance, overtime, esi_applicable, pf_applicable, lwf_applicable, bonus_applicable, gratuity_applicable, pt_applicable, remarks) values (${emp(code)}, '2026-04-01', ${t.basic}, ${t.hra}, 0, ${t.conveyance}, 0, ${t.site_allowance}, ${t.supervisor_allowance}, 0, ${t.esi_applicable}, ${t.pf_applicable}, ${t.lwf_applicable}, ${t.bonus_applicable}, ${t.gratuity_applicable}, ${t.pt_applicable}, 'Imported from Salary Master Data') on conflict do nothing;`);
}

for (const [month, code, site, days, amount, remarks] of OT_LOG)
  out.push(`insert into ot_incentives (month, employee_id, site, days, amount, remarks) values ('${month}', ${emp(code)}, ${q(site)}, ${days}, ${amount ?? "null"}, ${q(remarks)});`);

for (const [month, rows] of Object.entries(HISTORY)) {
  out.push(`-- ${monthLabel(month)}`);
  out.push(`insert into payroll_runs (month, status, payment_date, formula_set_id, formulas, notes) values ('${month}', 'draft', ${q(PAYMENT_DATES[month] ?? null)}, (select id from formula_sets where effective_from = '2026-04-01'), ${j(SHEET_FORMULAS_FY26)}, 'Imported from Google Sheet') on conflict (month) do nothing;`);
  rows.forEach(([code, w, o, l, inc, man], i) => {
    const e = employees[code];
    const snap = snapshotOf(e);
    const s = toStructure(STRUCTURES[code]);
    const inputs = { working_days: w, paid_offs: o, leaves: l, lop_days: 0, incentive: inc, arrears: 0, ex_gratia: 0, manual_adjustment: man, professional_tax: 0 };
    const r = computeLine(SHEET_FORMULAS_FY26, month, snap, s, inputs);
    out.push(`insert into payroll_lines (run_id, employee_id, print_code, snapshot, structure_id, structure, working_days, paid_offs, leaves, lop_days, incentive, arrears, ex_gratia, manual_adjustment, professional_tax, calc, gross, net_pay, ctc, error) values ((select id from payroll_runs where month = '${month}'), ${emp(code)}, 'C${i + 1}', ${j(snap)}, (select id from salary_structures where employee_id = ${emp(code)} and effective_from = '2026-04-01'), ${j(s)}, ${w}, ${o}, ${l}, 0, ${inc}, 0, 0, ${man}, 0, ${j(r.calc)}, ${r.gross}, ${r.net_pay}, ${r.ctc}, null) on conflict do nothing;`);
  });
  out.push(`update payroll_runs set status = 'finalized', finalized_at = now(), finalized_by = 'import' where month = '${month}';`);
}

out.push("commit;");
writeFileSync("supabase/seed.private.sql", out.join("\n") + "\n");
console.log(`Wrote supabase/seed.private.sql (${out.length} statements). Allowed logins: ${allowed.join(", ")}`);
